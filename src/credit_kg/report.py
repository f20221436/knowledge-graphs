"""Phase 9: generates outputs/reports/final_report.md from phase9_results.json.

Every number in the report is read from the results dictionary; verdict words ("reliable", "no reliable")
are derived from the intervals, so the text cannot drift from the computed results.
"""
from pathlib import Path

import pandas as pd

BANDS = ["Supportable in this scenario", "Review", "Not supportable in this scenario", "Insufficient behavioural evidence"]
SHORT = {"Supportable in this scenario": "Supportable", "Review": "Review",
         "Not supportable in this scenario": "Not supportable", "Insufficient behavioural evidence": "Insufficient evidence"}


def _pct(v, d=1):
    return f"{v * 100:.{d}f}%"


def _ci(lo, hi, d=4, sign=False):
    f = f"{{:{'+' if sign else ''}.{d}f}}"
    return f"[{f.format(lo)}, {f.format(hi)}]"


def _table(rows: list, cols: list) -> str:
    out = ["| " + " | ".join(h for h, _ in cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(fn(r)) for _, fn in cols) + " |" for r in rows]
    return "\n".join(out)


def _verdict(lo, hi):
    if lo > 0:
        return "reliable improvement"
    if hi < 0:
        return "reliably worse"
    return "no reliable difference"


def write_final_report(R: dict, path) -> None:
    abl = {r["feature_set"]: r for r in R["ablation_cv"]}
    tm = pd.DataFrame(R["test_metrics"]).set_index(["model", "metric"])
    rf, lr = R["paired_test"]["Random Forest: B - A"], R["paired_test"]["Logistic regression: LR-B - LR-A"]
    cal = R["calibration"]["summary"]
    cal_raw, cal_pd = cal["raw forest score, test"], cal["calibrated PD, test"]
    bands = pd.DataFrame(R["bands"])
    b3 = bands[(bands.scenario == "3 x typical payment") & (bands.version == "full score")].set_index("band")
    b3_free = bands[(bands.scenario == "3 x typical payment") & (bands.version == "model removed completely")].set_index("band")
    disp = pd.DataFrame(R["fairness_disparity"])
    audit = pd.DataFrame(R["fairness_audit"])
    gp = {r["pattern"][:3].strip(): r for r in R["graph_patterns"]}
    st, gnn, h = R["stability"], R["gnn"], R["health"]
    d3 = disp[disp.scenario == "3 x typical payment"]
    d30 = disp[disp.scenario == "fixed 30,000"]
    worst30 = d30.loc[d30.min_selection_ratio.idxmin()]

    L = []
    L += ["# Final report: knowledge-graph-driven credit risk and credit-increase analysis", "",
          f"*Generated by `{R['generated_by']}` on {R['generated_at']} from `outputs/reports/phase9_results.json`. Do not edit by hand.*", "",
          "> **The credit-increase score is a demonstrative scenario framework, not a lending policy.** The data contains no "
          "credit-increase requests or outcomes, and card payments are payment behaviour, not income.", "",
          "## 1. Question and short answer", "",
          "**Can a temporal knowledge graph of six months of card behaviour provide useful information for credit-risk "
          "modelling and for explainable credit-increase analysis?**", ""]
    L += [f"- **Random Forest + graph features:** {_verdict(rf['roc_ci_low'], rf['roc_ci_high'])} "
          f"(test ΔROC-AUC {rf['delta_roc_auc']:+.4f}, 95% CI {_ci(rf['roc_ci_low'], rf['roc_ci_high'], sign=True)}).",
          f"- **Logistic regression + graph features:** {_verdict(lr['roc_ci_low'], lr['roc_ci_high'])} "
          f"(test ΔROC-AUC {lr['delta_roc_auc']:+.4f}, 95% CI {_ci(lr['roc_ci_low'], lr['roc_ci_high'], sign=True)}; "
          f"CV {abl['LR-B']['delta_roc_auc']:+.4f}, B better in {abl['LR-B']['folds_better']} folds).",
          f"- **Graph neural network (graph only):** CV ROC-AUC {gnn['gnn_roc_auc']:.4f} vs {gnn['rf_a_roc_auc']:.4f} for the "
          f"engineered forest; difference {gnn['delta_vs_rf']:+.4f}, CI {_ci(*gnn['delta_ci'], sign=True)} ({_verdict(*gnn['delta_ci'])}).",
          f"- **Explanation:** the graph finds outcome-blind patterns that hold on the test set, e.g. late 3+ months in a row "
          f"→ {_pct(gp['Q2']['test_default_rate'])} missed the next payment; always paid in full → {_pct(gp['Q7']['test_default_rate'])} "
          f"(base rate {_pct(h['default_rate_test'])}).",
          f"- **Calibration:** the probability the score uses has Brier {cal_pd['brier']:.4f} (base-rate predictor "
          f"{cal_pd['brier_base_rate']:.4f}) and expected calibration error {cal_pd['ece']:.3f}.",
          f"- **Score vs outcomes (3 × typical payment, test):** {' → '.join(_pct(b3.loc[b, 'miss_rate']) for b in BANDS[:3])} "
          f"missed the next payment (Supportable → Review → Not supportable); with the model removed completely: "
          f"{' → '.join(_pct(b3_free.loc[b, 'miss_rate']) for b in BANDS[:3])}.",
          f"- **Fairness:** with requests sized to the customer, the lowest selection ratio is {d3.min_selection_ratio.min():.2f}; "
          f"with a fixed 30,000 it falls to {worst30.min_selection_ratio:.2f} ({worst30.attribute}).", ""]

    L += ["## 2. Pipeline health check", "",
          f"- Data: {h['customers']:,} unique customers, {h['monthly_rows']:,} monthly rows, test share {_pct(h['test_share'], 0)}, "
          f"default rate {_pct(h['default_rate_train'])} train / {_pct(h['default_rate_test'])} test."]
    g = R["graph"]
    if g["status"] == "checked":
        c = g["counts"]
        nodes = c["customers"] + c["accounts"] + c["monthly_records"] + c["states"]
        L += [f"- Graph: counts match exactly ({nodes:,} nodes, {sum(c.values()) - nodes:,} relationships), "
              f"{g['outcome_properties_on_nodes']} nodes and {g['outcome_properties_on_relationships']} relationships carry an outcome property, "
              f"{g['next_month_out_of_order']} `NEXT_MONTH` links out of order."]
    else:
        L += [f"- Graph: **{g['status']}**."]
    L += [f"- Tests: `{R['tests']['summary']}`.",
          f"- Terminology: {R['lint']['lines_mentioning']} lines mention income/salary; {R['lint']['problems']} problems "
          f"({R['lint']['self_references']} non-negated line(s) only describe the lint check itself).", ""]

    L += ["## 3. Data and graph patterns", "", "**Behaviour hypotheses (training customers).**", "",
          _table(R["patterns"], [("Hypothesis", lambda r: r["hypothesis"]), ("Verdict", lambda r: r["verdict"]),
                                 ("Default rate, lowest bucket", lambda r: _pct(r["rate_low_bucket"])),
                                 ("Default rate, highest bucket", lambda r: _pct(r["rate_high_bucket"]))]), "",
          "**Patterns found by Cypher (the graph never sees the outcome).**", "",
          _table(R["graph_patterns"], [("Pattern", lambda r: r["pattern"]), ("Customers", lambda r: f"{r['customers']:,}"),
                                       ("Train", lambda r: _pct(r["train_default_rate"])), ("Test", lambda r: _pct(r["test_default_rate"])),
                                       ("Lift", lambda r: f"{r['lift_vs_base']:.2f}×")]), ""]

    L += ["## 4. Ablation: does the graph help, and for which model?", "",
          "Cross-validation: 25 identical folds (5 × 5 repeated) on training customers; intervals use the Nadeau–Bengio correction "
          "for overlapping folds. Ablations were run in CV only; the test set was used once per final model.", "",
          _table(R["ablation_cv"], [("Model", lambda r: r["model"]), ("Features", lambda r: r["description"]),
                                    ("n", lambda r: r["n_features"]),
                                    ("CV ROC-AUC [95% CI]", lambda r: f"{r['cv_roc_auc']:.4f} {_ci(r['roc_ci_low'], r['roc_ci_high'])}"),
                                    ("Δ vs reference [95% CI]", lambda r: "reference" if r.get("delta_roc_auc") is None else
                                     f"{r['delta_roc_auc']:+.4f} {_ci(r['delta_ci_low'], r['delta_ci_high'], sign=True)}"),
                                    ("Folds better", lambda r: r.get("folds_better") or "–"),
                                    ("Verdict", lambda r: "–" if r.get("delta_roc_auc") is None else _verdict(r["delta_ci_low"], r["delta_ci_high"]))]), "",
          "**Test set (6,000 customers, 2,000 paired bootstrap resamples).**", "",
          _table(["RF A", "RF B", "LR-A", "LR-B"], [("Model", lambda m: m)] +
                 [(f"{lab} [95% CI]", lambda m, k=k: f"{tm.loc[(m, k), 'value']:.4f} {_ci(tm.loc[(m, k), 'ci_low'], tm.loc[(m, k), 'ci_high'])}")
                  for k, lab in [("roc_auc", "ROC-AUC"), ("pr_auc", "PR-AUC")]]), "",
          _table([("Random Forest: B − A", rf), ("Logistic regression: LR-B − LR-A", lr)],
                 [("Comparison", lambda r: r[0]), ("ΔROC-AUC [95% CI]", lambda r: f"{r[1]['delta_roc_auc']:+.4f} {_ci(r[1]['roc_ci_low'], r[1]['roc_ci_high'], sign=True)}"),
                  ("ΔPR-AUC [95% CI]", lambda r: f"{r[1]['delta_pr_auc']:+.4f} {_ci(r[1]['pr_ci_low'], r[1]['pr_ci_high'], sign=True)}"),
                  ("Verdict", lambda r: _verdict(r[1]["roc_ci_low"], r[1]["roc_ci_high"]))]), "",
          "Why: each customer's graph is a six-node chain built from the same 23 columns. A forest learns streaks and recoveries "
          "from the raw monthly columns directly; a linear model cannot, so for it the graph features add information. "
          f"On their own (credit limit + graph features) they reach {abl['graph_only']['cv_roc_auc']:.4f}, so they are informative but redundant for the forest.",
          "", "![ablation](../figures/final_ablation.png)", ""]

    L += ["## 5. Calibration", "",
          "The score reads the model output as a probability, so it must be calibrated. Model A, isotonic calibration inside "
          "cross-validation; test customers below.", "",
          _table([("Raw forest score", cal_raw), ("Calibrated PD (used by the score)", cal_pd)],
                 [("", lambda r: r[0]), ("Brier", lambda r: f"{r[1]['brier']:.4f}"), ("Brier skill vs base rate", lambda r: f"{r[1]['brier_skill']:+.3f}"),
                  ("ECE", lambda r: f"{r[1]['ece']:.3f}"), ("Mean predicted", lambda r: f"{r[1]['mean_predicted']:.3f}"),
                  ("Observed", lambda r: f"{r[1]['observed_rate']:.3f}"), ("Slope", lambda r: f"{r[1]['calibration_slope']:.2f}"),
                  ("Intercept", lambda r: f"{r[1]['calibration_intercept']:+.2f}")]), "",
          "![calibration](../figures/final_calibration.png)", ""]

    L += ["## 6. Credit-increase score vs real outcomes (test customers)", "",
          "Necessary, not sufficient: missing a payment is not the same as an increase going badly.", "",
          _table(bands.to_dict("records"), [("Request", lambda r: r["scenario"]), ("Version", lambda r: r["version"]),
                                            ("Label", lambda r: SHORT[r["band"]]), ("Customers", lambda r: f"{r['test_customers']:,}"),
                                            ("Missed next payment [95% CI]", lambda r: f"{_pct(r['miss_rate'])} [{_pct(r['ci_low'])}, {_pct(r['ci_high'])}]")]), "",
          f"Stability ({st['changes_tested']} one-at-a-time changes: weights ±20%, breakpoints ±10%): Spearman ≥ {st['min_spearman']:.3f}, "
          f"at most {_pct(st['max_band_flips'])} of labels change (worst: {st['worst_change']}).", ""]

    inv = R["fairness_invariance"]
    L += ["## 7. Fairness audit", "",
          f"Sex, age, education and marital status are not inputs to the model or the score (shuffling them changes "
          f"{'no' if inv['shuffle_invariant'] else 'SOME'} scores). Outcomes are still measured per group, because other inputs can correlate with them. "
          "All 30,000 customers; every probability is out-of-sample.", "",
          _table(R["fairness_disparity"], [("Request", lambda r: r["scenario"]), ("Attribute", lambda r: r["attribute"]),
                                           ("Lowest selection ratio", lambda r: f"{r['min_selection_ratio']:.2f}"),
                                           ("Supportable rate range", lambda r: f"{_pct(r['selection_rate_range'][0])} – {_pct(r['selection_rate_range'][1])}"),
                                           ("Miss rate if Supportable, range", lambda r: f"{_pct(r['miss_if_supportable_range'][0])} – {_pct(r['miss_if_supportable_range'][1])}"),
                                           ("Equal-opportunity gap", lambda r: f"{r['equal_opportunity_gap'] * 100:.1f} pts")]), "",
          "Selection ratio = group's Supportable rate ÷ most-favoured group's (0.8 is a common rule-of-thumb flag, not a legal test). "
          "Equal-opportunity gap = largest difference, among customers who did not miss a payment, in the share labelled Supportable.", "",
          "**Per group, 3 × typical payment.**", "",
          _table(audit[audit.scenario == "3 x typical payment"].to_dict("records"),
                 [("Attribute", lambda r: r["attribute"]), ("Group", lambda r: r["group"]), ("n", lambda r: f"{int(r['n']):,}"),
                  ("Supportable", lambda r: _pct(r["selection_rate"])), ("Ratio", lambda r: f"{r['selection_ratio_vs_max']:.2f}"),
                  ("Observed miss rate", lambda r: _pct(r["observed_miss_rate"])), ("Mean predicted", lambda r: _pct(r["mean_pd"])),
                  ("Missed if Supportable [95% CI]", lambda r: f"{_pct(r['miss_rate_if_supportable'])} [{_pct(r['miss_if_sup_ci_low'])}, {_pct(r['miss_if_sup_ci_high'])}]"),
                  ("Supportable among non-missers", lambda r: _pct(r["supportable_among_non_missers"]))]), "",
          "**Where gaps come from.** Group medians of the inputs that size a request:", "",
          _table(R["fairness_drivers"], [("Attribute", lambda r: r["attribute"]), ("Group", lambda r: r["group"]),
                                         ("Median limit", lambda r: f"{r['median_limit']:,.0f}"),
                                         ("Median typical payment", lambda r: f"{r['median_typical_payment']:,.0f}"),
                                         ("Mean late months", lambda r: f"{r['mean_late_months']:.2f}"),
                                         ("Points from predicted risk", lambda r: f"{r['pts_model_risk']:+.1f}")]), "",
          "**Inside the Supportable label** (3 × typical payment): predicted vs observed miss rate. Observed above predicted "
          "means the model under-predicts that group's risk inside the band.", "",
          _table(R["fairness_within_supportable"], [("Attribute", lambda r: r["attribute"]), ("Group", lambda r: r["group"]),
                                                    ("Supportable customers", lambda r: f"{int(r['n']):,}"),
                                                    ("Mean predicted", lambda r: _pct(r["mean_predicted"])),
                                                    ("Observed", lambda r: _pct(r["observed"])),
                                                    ("Observed − predicted", lambda r: f"{r['observed_minus_predicted'] * 100:+.1f} pts"),
                                                    ("Mean score", lambda r: f"{r['mean_score']:.1f}")]), "",
          "**Proxy strength** (cross-validated ROC-AUC of predicting the attribute from the score's inputs; 0.5 = no information):", "",
          _table(R["fairness_proxy"], [("Attribute", lambda r: r["attribute"]), ("ROC-AUC", lambda r: f"{r['roc_auc_from_score_inputs']:.3f}")]), "",
          f"Test customers only (3 × typical payment): lowest selection ratio "
          f"{min(r['min_selection_ratio'] for r in R['fairness_disparity_test_only']):.2f}, largest equal-opportunity gap "
          f"{max(r['equal_opportunity_gap'] for r in R['fairness_disparity_test_only']) * 100:.1f} pts.", "",
          "Nothing was changed in response to this audit. Remedies (group-specific cut-offs, reweighting, a different request rule) are policy decisions.", "",
          "![fairness](../figures/final_fairness.png)", ""]

    L += ["## 8. Limitations", "",
          "- **Old, narrow data:** one bank, Taiwan, April–September 2005; six months, one card per customer, no links between customers.",
          "- **No income:** payments are what customers paid toward the card; affordability cannot be judged directly.",
          "- **No real credit-increase outcomes:** the request is a chosen scenario; the score can be shown to be consistent and traceable, not correct.",
          "- **Hand-set weights:** judgement calls; data set the breakpoints and the order of importance; request-vs-limit breakpoints are a policy assumption.",
          "- **Observational model:** nothing is causal; the projected limit is never fed back into the model.",
          "- **The graph adds explanation, not accuracy, for strong models:** it is built from the same 23 columns the models see.",
          "- **Fairness audit is descriptive:** four recorded attributes with coarse, partly undocumented codes; rule-of-thumb reference points, not a legal standard.",
          "- **Single fixed split** (80/20, seed 42); intervals cover resampling noise, not a change of population.", ""]

    L += ["## 9. Conclusion", "",
          f"For **prediction**, the knowledge graph helps only a simple model: logistic regression gains {lr['delta_roc_auc']:+.4f} ROC-AUC on the test set "
          f"({_verdict(lr['roc_ci_low'], lr['roc_ci_high'])}), while the Random Forest moves {rf['delta_roc_auc']:+.4f} ({_verdict(rf['roc_ci_low'], rf['roc_ci_high'])}), "
          f"because it already learns the same patterns from the raw monthly columns. Every approach, including a graph neural network, tops out around "
          f"0.78–0.79, the limit of what these 23 columns contain. For **explanation**, the graph is useful: without seeing outcomes it finds patterns such as "
          f"three late months in a row ({_pct(gp['Q2']['test_default_rate'], 0)} then miss a payment) and supplies the month-by-month evidence behind each decision. "
          f"The credit-increase score built on top uses calibrated probabilities, is stable to its hand-set weights, sorts real outcomes in the right order even "
          f"with the model removed, and treats demographic groups similarly when the request is sized to the customer's own payments, which a fixed-size request "
          f"does not. It remains a demonstration of transparent reasoning, not a validated lending decision.", "",
          "## 10. Reproduce", "",
          "```powershell",
          ".\\.venv\\Scripts\\jupyter.exe nbconvert --to notebook --execute --inplace notebooks\\09_final_evaluation.ipynb --ExecutePreprocessor.timeout=1800",
          "```", "Requires notebooks 01–08 to have been run (their output files) and, for the graph checks, Neo4j running.", ""]

    Path(path).write_text("\n".join(L), encoding="utf-8")
