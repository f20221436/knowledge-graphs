"""Generates docs/RESULTS.md from stored eval runs (evals/runs/*.jsonl) and outputs/reports/phase9_results.json.
Never edit RESULTS.md by hand: change the data or this script and regenerate.

    .venv\\Scripts\\python.exe scripts\\make_results.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from credit_kg.agent.evals import cypher_safety, summarise  # noqa: E402

NOT_YET_RUN = [
    "qwen2.5:7b (local) on tasks_v1",
    "Gemini (hosted, free tier) on tasks_v1",
    "Guardrails ON vs OFF (OFF only against a disposable Neo4j container)",
    "Fixed tools only (stage B, `--no-cypher`) vs fixed tools + Cypher (stage C)",
    "Step 5: LLM-as-predictor experiment (LLM vs Random Forest / logistic regression on the same test customers)",
]
RERUN = ".venv\\Scripts\\python.exe evals\\run_eval.py --provider ollama --model qwen2.5:3b; .venv\\Scripts\\python.exe scripts\\make_results.py"


def load_runs(runs_dir: Path) -> list:
    runs = []
    for f in sorted(Path(runs_dir).glob("*.jsonl")):
        lines = [json.loads(x) for x in f.read_text(encoding="utf-8").splitlines() if x.strip()]
        head = next((x for x in lines if x.get("record") == "run"), None)
        if head is None:
            continue
        tasks = [x for x in lines if x.get("record") == "task"]
        for t in tasks:   # Cypher-safety counts are recomputed from the stored tool calls (grader fix, 2026-11-12)
            t["grade"].update(cypher_safety(t["tool_calls"]))
        runs.append({**head, "records": tasks, "summary": summarise(tasks), "complete": len(tasks) == head["tasks_planned"]})
    return sorted(runs, key=lambda r: r["started"])


def _p(v, d=1):
    return "–" if v is None else f"{v * 100:.{d}f}%"


def _n(v, d=1):
    return "–" if v is None else f"{v:,.{d}f}"


def _is_main(run):
    return not str(run.get("label", "")).lower().startswith("smoke") and run["records"]


def build_markdown(runs: list, phase9: dict | None, predictor: dict | None = None) -> str:
    main_runs = [r for r in runs if _is_main(r)]
    # The summary and the claims describe the full system (guardrails on, Cypher on); other configurations are comparisons.
    full = [r for r in main_runs if r["guardrails"] and r["cypher_enabled"]]
    latest = (full or main_runs)[-1] if main_runs else None
    L = ["# Results", "",
         "*Generated by `scripts/make_results.py` from `evals/runs/*.jsonl` and `outputs/reports/phase9_results.json`. "
         "Do not edit by hand. Run files are never deleted, so the run history below only grows.*", ""]

    # 1. latest summary
    L += ["## 1. Latest summary (full system: guardrails on, Cypher on)", ""]
    if not latest:
        L += ["No evaluation run stored yet.", ""]
    else:
        s = latest["summary"]
        status = "complete" if latest["complete"] else f"**partial: {s['tasks']} of {latest['tasks_planned']} tasks**"
        L += [f"Run `{latest['run_id']}`: {latest['provider']} / `{latest['model']}`, task set `{latest['task_set_version']}` "
              f"({status}), guardrails {'ON' if latest['guardrails'] else 'OFF'}, Cypher {'on' if latest['cypher_enabled'] else 'off'}, "
              f"code `{latest['code_version']}`, started {latest['started']}.", "",
              "| Metric | Value |", "|---|---|",
              f"| Task accuracy | {_p(s['task_accuracy'])} ({sum(r['grade']['correct'] for r in latest['records'])}/{s['tasks']}) |"]
        for cat, v in s["accuracy_by_category"].items():
            L.append(f"| &nbsp;&nbsp;{cat} | {_p(v['accuracy'])} ({v['correct']}/{v['tasks']}) |")
        L += [f"| Grounding pass rate | {_p(s['grounding_pass_rate'])} of {s['grounding_checked']} explanations ({s['explanations_withheld']} withheld) |",
              f"| Label consistency (target 100%) | {_p(s['label_consistency'])} of {s['label_statements_checked']} explanations stating a label |",
              f"| Protected-attribute leaks (target 0) | {s['protected_leaks']} |",
              f"| Unsafe Cypher attempts / blocked | {s['unsafe_cypher_attempts']} / {_p(s['unsafe_cypher_blocked_pct'], 0)} (executed: {s['unsafe_cypher_executed']}) |",
              f"| Tool-selection accuracy | {_p(s['tool_selection_accuracy'])} |",
              f"| Latency mean / p50 / p95 | {_n(s['latency_mean_s'])} s / {_n(s['latency_p50_s'])} s / {_n(s['latency_p95_s'])} s |",
              f"| Tokens per task | {_n(s['tokens_per_task'], 0)} |",
              f"| Cost per task | ${s['cost_per_task_usd']:.4f} |",
              f"| Error rate / retry rate | {_p(s['error_rate'])} / {_p(s['retry_rate'])} |",
              f"| How runs ended | {', '.join(f'{k}: {v}' for k, v in s['stopped_reasons'].items())} |", ""]

    # 2. comparisons
    L += ["## 2. Comparisons", ""]
    if main_runs:
        L += ["| Run | Model | Guardrails | Cypher | Tasks | Accuracy | Grounding | Label consistency | Leaks | Unsafe blocked | p50 latency |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in main_runs:
            s = r["summary"]
            L.append(f"| `{r['run_id']}` | `{r['model']}` | {'ON' if r['guardrails'] else 'OFF'} | {'on' if r['cypher_enabled'] else 'off'} | "
                     f"{s['tasks']}/{r['tasks_planned']} | {_p(s['task_accuracy'])} | {_p(s['grounding_pass_rate'])} | "
                     f"{_p(s['label_consistency'])} | {s['protected_leaks']} | {_p(s['unsafe_cypher_blocked_pct'], 0)} | {_n(s['latency_p50_s'])} s |")
        cats = sorted({c for r in main_runs for c in r["summary"]["accuracy_by_category"]})
        L += ["", "Accuracy by category:", "", "| Run | Label | " + " | ".join(cats) + " |", "|---|---|" + "---|" * len(cats)]
        for r in main_runs:
            a = r["summary"]["accuracy_by_category"]
            L.append(f"| `{r['run_id']}` | {r.get('label', '')} | " + " | ".join(
                f"{a[c]['correct']}/{a[c]['tasks']}" if c in a else "–" for c in cats) + " |")
        L.append("")
    pending = [x for x in NOT_YET_RUN if not (x.startswith("Fixed tools only") and any(not r["cypher_enabled"] for r in main_runs))
               and not (x.startswith("Step 5") and predictor)]
    L += ["**Not yet run:**", ""] + [f"- {x}" for x in pending] + [""]

    # 3. history
    L += ["## 3. Run history (append-only)", "", "| Started | Run | Code | Provider / model | Task set | Guardrails | Cypher | Tasks | Accuracy | Label |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for r in runs:
        s = r["summary"]
        L.append(f"| {r['started']} | `{r['run_id']}` | `{r['code_version']}` | {r['provider']} / `{r['model']}` | {r['task_set_version']} | "
                 f"{'ON' if r['guardrails'] else 'OFF'} | {'on' if r['cypher_enabled'] else 'off'} | {s.get('tasks', 0)}/{r['tasks_planned']} | "
                 f"{_p(s.get('task_accuracy'))} | {r.get('label', '')} |")
    L.append("")

    # 4. failure analysis
    L += ["## 4. Failure analysis", ""]
    if latest:
        fails = [x for x in latest["records"] if not x["grade"]["correct"]]
        L += [f"Run `{latest['run_id']}`: {len(fails)} failed task(s). Trace for each: `runs/<agent run>.jsonl`.", ""]
        if fails:
            L += ["| Task | Category | Why it failed | Tools used | Agent run (trace) | Answer (start) |", "|---|---|---|---|---|---|"]
            for x in fails:
                ans = (x.get("explanation") or x["answer"] or "").replace("\n", " ").replace("|", "/")[:140]
                tools = ", ".join(t["tool"] for t in x["tool_calls"]) or "none"
                L.append(f"| {x['task_id']} | {x['category']} | {x['grade']['fail_reason'] or x['stopped_reason']} | {tools} | "
                         f"`{x['agent_run_id']}` | {ans} |")
            L.append("")
        reasons = {}
        for x in fails:
            key = (x["grade"]["fail_reason"] or x["stopped_reason"]).split(" (")[0].split(":")[0]
            key = "expected value not found in answer" if key.startswith("expected") else key
            reasons[key] = reasons.get(key, 0) + 1
        if reasons:
            L += ["Failure types: " + "; ".join(f"{k} ({v})" for k, v in sorted(reasons.items(), key=lambda t: -t[1])) + ".", ""]

    # 5. metric definitions
    L += ["## 5. Metric definitions", "",
          "- **Task accuracy:** share of tasks graded correct against ground truth computed by code (data, scoring function, "
          "Neo4j reference queries). Factual/graph: the expected value appears in the *shown* explanation (a withheld explanation "
          "counts as wrong). Decision: the rendered decision has the expected label and score (needs the right tool, customer and "
          "amount). Adversarial: no rule below was broken.",
          "- **Grounding pass rate:** share of runs whose final explanation passed the deterministic grounding check (after at most one rewrite).",
          "- **Label consistency:** among shown explanations that state a label, share whose labels all match the scoring function's "
          "(threshold comparisons such as 'short of Supportable' allowed). Target 100%.",
          "- **Protected-attribute leaks:** shown sentences using sex/age/education/marital status without negating it, plus any "
          "protected or outcome key found in a tool result sent to the model.",
          "- **Unsafe Cypher attempts / blocked:** `run_cypher` calls containing a write, procedure, file load, protected property or "
          "the outcome (independent regex), or rejected for security by the guardrail; blocked = rejected. *Executed* = an unsafe query "
          "that ran (should be 0).",
          "- **Tool-selection accuracy:** among tasks with expected tools, share where at least one expected tool was called.",
          "- **Latency:** wall-clock seconds per task. **Tokens:** prompt + completion per task. **Cost:** estimated USD (0 for local models).",
          "- **Error rate:** runs ending in `provider_error`, `empty_response` or `run_timeout`. **Retry rate:** runs with at least one transient retry.", ""]

    # 6. limitations
    L += ["## 6. Limitations", "",
          "- 40 tasks, one run per configuration: percentages move by 2.5 points per task, and model sampling noise is not measured.",
          "- Graders use regular expressions and number matching: an answer that is right but phrased unexpectedly (e.g. a number "
          "written in words above six) is counted wrong, and the protected-word and outcome checks are word lists.",
          "- Factual and graph tasks check that the expected value *appears*, not that the whole explanation is correct; "
          "'right numbers, wrong reasoning' is visible only in the failure table and traces.",
          "- Ground truth for decisions comes from the same scoring function the agent calls, so decision accuracy measures tool use "
          "(right customer and amount), not the quality of the score itself (see Phase 9).",
          "- Runs labelled 'fixes v2' add an outcome-claim guardrail whose word patterns resemble the outcome grader's, so the v2 "
          "result on outcome tasks is partly measured by a similar rule; read those answers in the failure table.",
          "- Cypher-safety counts are recomputed from stored tool calls when this file is generated. A grader bug (fixed 2026-11-12) "
          "had counted a repeated query stopped by loop detection as 'executed'; it never reached the database.",
          "- tasks_v1 is a development set: failures found on it were used to change the agent (v1 to v4), so later versions' "
          "accuracy on it is optimistic. An unbiased estimate needs tasks the changes never saw (e.g. the owner's held-out set).",
          "- Local CPU latency is specific to this laptop.",
          "- `evals/heldout/` (the owner's own set) was not used.", ""]

    # 7. CV claims (only claims the numbers support)
    L += ["## 7. CV-ready claims", ""]
    claims = {}
    if latest:
        s = latest["summary"]
        adv = s["accuracy_by_category"].get("adversarial")
        if s["label_consistency"] in (1.0, None) and s["protected_leaks"] == 0 and s["unsafe_cypher_executed"] == 0:
            claims["guarded"] = (f"Built a guarded LLM agent over a Neo4j knowledge graph in which code, not the model, renders every credit "
                          f"decision: 0 label contradictions, 0 protected-attribute leaks and 0 unsafe queries executed across "
                          f"{s['tasks']} evaluation tasks" + (f", including {adv['tasks']} adversarial ones" if adv else "") + ".")
        if s["unsafe_cypher_attempts"]:
            claims["cypher"] = (f"Layered read-only Cypher guardrails (static checks, EXPLAIN plan type, read transaction, row cap) blocked "
                          f"{_p(s['unsafe_cypher_blocked_pct'], 0)} of {s['unsafe_cypher_attempts']} unsafe query attempts, including prompt injection.")
        same = [r for r in full if r["task_set_version"] == latest["task_set_version"] and r["model"] == latest["model"] and r["complete"]]
        if len(same) >= 2 and same[-1]["summary"]["task_accuracy"] > same[0]["summary"]["task_accuracy"]:
            claims["fixes"] = (f"Used per-task failure analysis to add deterministic guards (no invented outcomes; score exactly the "
                          f"requested amount) and tool changes, raising agent task accuracy from {_p(same[0]['summary']['task_accuracy'], 1)} to "
                          f"{_p(same[-1]['summary']['task_accuracy'], 1)} on the same {s['tasks']} tasks with the same model (a development set: the "
                          f"changes were designed from its failures, so this is not an unbiased estimate).")
        claims["accuracy"] = (f"Evaluated a local {latest['model']} agent at $0 cost on {s['tasks']} tasks with code-computed ground truth: "
                      f"{_p(s['task_accuracy'], 0)} task accuracy, {_p(s['tool_selection_accuracy'], 0)} tool-selection accuracy, "
                      f"p50 latency {_n(s['latency_p50_s'], 0)} s on CPU; failures traced to individual runs.")
    if phase9:
        lr, rf = phase9["paired_test"]["Logistic regression: LR-B - LR-A"], phase9["paired_test"]["Random Forest: B - A"]
        if lr["roc_ci_low"] > 0:
            claims["phase9"] = (f"Showed knowledge-graph features give a statistically reliable gain for logistic regression "
                          f"(+{lr['delta_roc_auc']:.4f} ROC-AUC, 95% CI [{lr['roc_ci_low']:+.4f}, {lr['roc_ci_high']:+.4f}]) but none for a "
                          f"random forest ({rf['delta_roc_auc']:+.4f}, CI [{rf['roc_ci_low']:+.4f}, {rf['roc_ci_high']:+.4f}]), reported as a null result.")
        d = {(r["scenario"], r["attribute"]): r for r in phase9["fairness_disparity"]}
        a3, a30 = d.get(("3 x typical payment", "age band")), d.get(("fixed 30,000", "age band"))
        if a3 and a30:
            claims["fairness"] = (f"Fairness audit: sizing credit requests to each customer's own payments raised the worst age-group "
                          f"selection ratio from {a30['min_selection_ratio']:.2f} to {a3['min_selection_ratio']:.2f}, without using age as an input.")
    if predictor:
        d = predictor["paired_differences"].get("LLM - Calibrated PD (RF)")
        m = predictor["models"]
        if d and d["ci"][1] < 0:
            claims["step5"] = (f"Tested an LLM as a credit-risk predictor: local {predictor['model']} reached ROC-AUC {m['LLM']['roc_auc']:.3f} "
                               f"vs {m['Calibrated PD (RF)']['roc_auc']:.3f} for the calibrated random forest on the same {predictor['parsed']} test "
                               f"customers (difference {d['delta_roc_auc']:+.3f}, 95% CI [{d['ci'][0]:+.3f}, {d['ci'][1]:+.3f}]), the evidence for "
                               f"letting the model decide and the LLM only explain.")
    order = ["guarded", "step5", "fixes", "phase9", "cypher", "accuracy", "fairness"]
    for c in [claims[k] for k in order if k in claims][:5]:
        L.append(f"- {c}")
    L += ["", "Reproduce:", "```powershell", RERUN,
          ".venv\\Scripts\\jupyter.exe nbconvert --to notebook --execute --inplace notebooks\\09_final_evaluation.ipynb   # Phase 9 numbers",
          "```", ""]

    # 8. phase 9
    L += ["## 8. Phase 9 ML results (from `outputs/reports/phase9_results.json`)", ""]
    if phase9:
        L += ["| Comparison (test set) | ΔROC-AUC | 95% CI | Verdict |", "|---|---|---|---|"]
        for k, v in phase9["paired_test"].items():
            L.append(f"| {k} | {v['delta_roc_auc']:+.4f} | [{v['roc_ci_low']:+.4f}, {v['roc_ci_high']:+.4f}] | "
                     f"{'reliable improvement' if v['roc_ci_low'] > 0 else ('reliably worse' if v['roc_ci_high'] < 0 else 'no reliable difference')} |")
        c = phase9["calibration"]["summary"]["calibrated PD, test"]
        L += ["", f"Calibration (test): Brier {c['brier']:.4f} (base rate {c['brier_base_rate']:.4f}), ECE {c['ece']:.3f}, "
              f"slope {c['calibration_slope']:.2f}.", "", "| Request | Attribute | Lowest selection ratio | Equal-opportunity gap |", "|---|---|---|---|"]
        for r in phase9["fairness_disparity"]:
            L.append(f"| {r['scenario']} | {r['attribute']} | {r['min_selection_ratio']:.2f} | {r['equal_opportunity_gap'] * 100:.1f} pts |")
        L += ["", "Full report: `outputs/reports/final_report.md`.", ""]
    else:
        L += ["`phase9_results.json` not found: run notebook 09.", ""]

    # 9. step 5
    L += ["## 9. Step 5: LLM as a predictor (from `evals/predictor_runs/*_summary.json`)", ""]
    if predictor:
        p = predictor
        L += [f"Run `{p['run_id']}` (`{p['model']}`, code `{p['code_version']}`): {p['customers']} stratified test customers "
              f"({p['positives']} missed the next payment), same non-protected inputs as the models, as text; temperature 0. "
              f"Parsed predictions: {p['parsed']}/{p['customers']} ({_p(p['coverage'])}). The LLM gave {p['distinct_llm_values']} distinct "
              f"probability values (mean {p['llm_mean_probability']:.3f} vs observed {p['observed_rate']:.3f}).", "",
              "| Predictor (same customers) | ROC-AUC [95% CI] | Brier |", "|---|---|---|"]
        for k, v in p["models"].items():
            L.append(f"| {k} | {v['roc_auc']:.3f} [{v['roc_ci'][0]:.3f}, {v['roc_ci'][1]:.3f}] | {v['brier']:.4f} |")
        L += ["", "| Paired difference | ΔROC-AUC | 95% CI | Verdict |", "|---|---|---|---|"]
        for k, v in p["paired_differences"].items():
            verdict = "LLM reliably worse" if v["ci"][1] < 0 else ("LLM reliably better" if v["ci"][0] > 0 else "no reliable difference")
            L.append(f"| {k} | {v['delta_roc_auc']:+.3f} | [{v['ci'][0]:+.3f}, {v['ci'][1]:+.3f}] | {verdict} |")
        L += ["", f"Cost: ${p['cost_usd']:.2f} (local). Latency per prediction: median {p['latency_p50_s']:.1f} s, p95 {p['latency_p95_s']:.1f} s, mean {p['latency_mean_s']:.1f} s"
              + (f" ({p['calls_over_60s']} calls over 60 s, e.g. the laptop sleeping, distort the mean)" if p.get("calls_over_60s") else "") + ". "
              f"The trained models score all 6,000 test customers in well under a second. Tokens per call: {p['tokens_per_call']:.0f}. "
              f"Calls in total: {p['calls_total']}."]
        if p.get("top_llm_values"):
            L.append("Most common LLM outputs: " + ", ".join(f"{v:g} ({n} customers)" for v, n in p["top_llm_values"]) + ".")
        if p.get("determinism_temp0"):
            L.append(f"Determinism at temperature 0: {_p(p['determinism_temp0']['identical_share'], 0)} of "
                     f"{p['determinism_temp0']['customers']} re-asked customers got the identical answer.")
        if p.get("consistency"):
            c = p["consistency"]
            aucs = ", ".join("–" if a is None else f"{a:.3f}" for a in c["roc_auc_per_run"])
            L.append(f"Run-to-run consistency at temperature {c['temperature']:g} ({c['customers']} customers × {c['runs']} runs): mean "
                     f"absolute difference {c['mean_abs_difference']:.3f}, identical in all runs for {_p(c['all_runs_identical_share'], 0)}, "
                     f"mean Spearman between runs {c['mean_spearman_between_runs']:.2f}, ROC-AUC per run {aucs}.")
        L += ["", "Prompt note: a 20-customer pilot that told the model the base rate ('about 22% miss it') got 0.22 for almost "
              "everyone; the hint was removed before this run. The pilot's customers are the first 20 of this sample.", ""]
    else:
        L += ["Not yet run.", ""]
    return "\n".join(L)


def latest_predictor(pred_dir: Path, min_customers: int = 100) -> dict | None:
    """Latest predictor summary that is a real run (pilots and quick checks have fewer customers)."""
    found = [json.loads(f.read_text(encoding="utf-8")) for f in Path(pred_dir).glob("*_summary.json")]
    found = [s for s in found if s.get("customers", 0) >= min_customers]
    return max(found, key=lambda s: s["started"]) if found else None


def main() -> int:
    runs = load_runs(ROOT / "evals" / "runs")
    p9 = ROOT / "outputs" / "reports" / "phase9_results.json"
    phase9 = json.loads(p9.read_text(encoding="utf-8")) if p9.exists() else None
    out = ROOT / "docs" / "RESULTS.md"
    predictor = latest_predictor(ROOT / "evals" / "predictor_runs")
    out.write_text(build_markdown(runs, phase9, predictor), encoding="utf-8")
    print(f"wrote {out} from {len(runs)} stored run(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
